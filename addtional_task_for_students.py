def my_count(l: list, item) -> int:
    """
    Подсчитывает количество вхождений элемента в список.

    Параметры:
        l (list): Список, в котором производится поиск
        item: Элемент, количество вхождений которого нужно подсчитать

    Возвращает:
        int: Количество вхождений элемента в список

    Примеры:
        >>> my_count([1, 2, 3, 2, 4, 2], 2)
        3
        >>> my_count(['a', 'b', 'a', 'c'], 'a')
        2
        >>> my_count([], 1)
        0
    """
    count = 0
    for element in l:
        if element == item:
            count += 1
    return count
